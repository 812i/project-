import streamlit as st

# إعداد صفحة التطبيق للجوال
st.set_page_config(
    page_title="World Cleanup Day",
    page_icon="🌍",
    layout="centered"
)

st.title("🌍 حاسبة الاستدامة واليوم العالمي للتنظيف")
st.write("أداتك التفاعلية لحساب البصمة اليومية ومعرفة أثرك في الحد من النفايات بمناسبة اليوم العالمي للتنظيف (20 سبتمبر).")

st.markdown("---")

# إدخال المستخدم
st.subheader("📊 حدد معدل استهلاكك اليومي والأسبوعي:")

plastic_bottles = st.slider("كم عدد قوارير البلاستيك التي تستخدمها يومياً؟", 0, 10, 2)
paper_bags = st.slider("كم عدد الأكياس أو الأوراق المهدرة أسبوعياً؟", 0, 20, 5)
organic_food = st.selectbox("كيف تتعامل مع بقايا الطعام الفائضة؟", [
    "أتخلص منها بشكل مستمر بدون تدوير", 
    "أحاول تقليلها قدر الإمكان", 
    "أستفيد منها أو أحولها لسماد منزلي"
])

st.markdown("---")

if st.button("احسب أثرك البيئي الآن", type="primary"):
    # حسابات تقريبية دقيقة
    plastic_yearly = plastic_bottles * 365
    paper_yearly = paper_bags * 52
    co2_saved = (plastic_yearly * 0.08) + (paper_yearly * 0.01) # كجم من الكربون الموفر بالتدوير
    
    st.success("### 📈 تقريرك البيئي لليوم العالمي للتنظيف:")
    st.write(f"• استهلاكك السنوي من البلاستيك: **{plastic_yearly} قارورة**.")
    st.write(f"• استهلاكك السنوي من الورق/الأكياس: **{paper_yearly} وحدة**.")
    st.write(f"• إجمالي انبعاثات الكربون الناتجة عن نفاياتك: تقريباً **{co2_saved:.1f} كجم** سنوياً.")
    
    st.markdown("---")
    st.subheader("💡 تقييم السلوك البيئي:")

    # تقييم منطقي يربط البلاستيك وتصرف الطعام معاً بشكل سليم
    if plastic_bottles <= 2 and organic_food == "أستفيد منها أو أحولها لسماد منزلي":
        st.success("🌟 **مستوى استدامة ممتاز!** استهلاكك منخفض وعنايتك بالنفايات العضوية تعكس وعياً بيئياً عالياً يساهم بقوة في نظافة وحماية الكوكب.")
    elif plastic_bottles >= 7 or organic_food == "أتخلص منها بشكل مستمر بدون تدوير":
        st.warning("⚠️ **تنبيه بيئي:** معدل استهلاكك العالي للنفايات يضع عبئاً على مكبات البلدية. ننصحك بالتحول إلى بدائل قابلة لإعادة الاستخدام وتقليل هدر الطعام احتفالاً باليوم العالمي للتنظيف!")
    else:
        st.info("💡 **استهلاك متوسط:** أنت في الطريق الصحيح، لكن يمكنك تحسين عاداتك اليومية من خلال إعادة تدوير القوارير والأوراق لتقليل أثرك البيئي.")
        
    st.balloons()

st.markdown("---")
st.markdown("<p style='text-align: center; color: gray;'>World Cleanup Day • Mobile Edition (20 Sept)</p>", unsafe_allow_html=True)
